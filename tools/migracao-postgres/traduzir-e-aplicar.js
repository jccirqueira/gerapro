// Traduz o DDL do SQLite (data/gerapro.db) para PostgreSQL e aplica no banco local.
// Uso (a partir da raiz do repo):  node tools/migracao-postgres/traduzir-e-aplicar.js
// Requer: npm install pg  (entra em package.json na Fase 2)
// Conexão: variáveis PG* ou padrão localhost:5433 (embedded-postgres local — ver docs/migracao-postgres-fase1.md)
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const { Client } = require('pg');

const REPO = path.join(__dirname, '..', '..');
const SRC_SQLITE = path.join(REPO, 'data', 'gerapro.db');
const OUT = path.join(__dirname, 'postgres-schema.sql');

const PG_CONF = {
  host: process.env.PGHOST || 'localhost',
  port: +(process.env.PGPORT || 5433),
  user: process.env.PGUSER || 'gerapro',
  password: process.env.PGPASSWORD || 'gerapro_local_2026',
  database: process.env.PGDATABASE || 'gerapro',
};

const q = (id) => '"' + String(id).trim().replace(/"/g, '""') + '"';
const qList = (lista) => lista.split(',').map(s => q(s)).join(', ');

// ── 1. Extrai os objetos do sqlite_master ──
const sqlite = new DatabaseSync(SRC_SQLITE, { readOnly: true });
const objs = sqlite
  .prepare("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY type, name")
  .all()
  .map(r => ({ tipo: r.type, nome: r.name, sql: r.sql }));
sqlite.close();

const tabelas = objs.filter(o => o.tipo === 'table' && !o.nome.startsWith('sqlite_'));
const indices = objs.filter(o => o.tipo === 'index' && !o.nome.startsWith('sqlite_'));
console.log('tabelas(app): ' + tabelas.length + ' | índices: ' + indices.length);

// ── 2. Tradução ──
function splitTop(body) {
  const out = []; let depth = 0, cur = '';
  for (const ch of body) {
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur); cur = ''; }
    else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out;
}

const RE_FK_INLINE = /\bREFERENCES\s+([A-Za-z_0-9]+)\s*\(([^)]+)\)\s*(ON DELETE\s+(CASCADE|RESTRICT|SET NULL|SET DEFAULT))?\s*(ON UPDATE\s+(CASCADE|RESTRICT|SET NULL|SET DEFAULT))?/i;
const RE_FK_TABLE = /^FOREIGN KEY\s*\(([^)]+)\)\s*REFERENCES\s+([A-Za-z_0-9]+)\s*\(([^)]+)\)\s*(ON DELETE\s+(CASCADE|RESTRICT|SET NULL|SET DEFAULT))?\s*(ON UPDATE\s+(CASCADE|RESTRICT|SET NULL|SET DEFAULT))?/i;

const criaTabelas = [];
const alterFks = [];
let nAutoInc = 0;

for (const t of tabelas) {
  let sql = t.sql.replace(/;\s*$/, '');
  if (/INTEGER PRIMARY KEY AUTOINCREMENT/i.test(sql)) {
    sql = sql.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/i, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    nAutoInc++;
  }
  const m = sql.match(/^CREATE TABLE\s+([A-Za-z_0-9]+)\s*\(([\s\S]*)\)\s*$/i);
  if (!m) { console.log('!! não parseou: ' + t.nome); continue; }
  const nome = m[1];
  const segs = splitTop(m[2]);
  const keep = [];
  for (let seg of segs) {
    let s = seg.trim();
    if (!s) continue;
    const fkT = s.match(RE_FK_TABLE);
    if (fkT) {
      alterFks.push(`ALTER TABLE ${q(nome)} ADD FOREIGN KEY (${qList(fkT[1])}) REFERENCES ${q(fkT[2])}(${qList(fkT[3])})${fkT[4] ? ' ' + fkT[4].toUpperCase() : ''}${fkT[6] ? ' ' + fkT[6].toUpperCase() : ''};`);
      continue;
    }
    if (/^(PRIMARY KEY|UNIQUE|CHECK)\b/i.test(s)) {
      keep.push(s.replace(/^((?:PRIMARY KEY|UNIQUE)\s*\()([^)]+)(\))/i, (all, a, cols, b) => a + qList(cols) + b));
      continue;
    }
    const fkC = s.match(RE_FK_INLINE);
    if (fkC) {
      const col = s.split(/\s+/)[0];
      alterFks.push(`ALTER TABLE ${q(nome)} ADD FOREIGN KEY (${q(col)}) REFERENCES ${q(fkC[1])}(${qList(fkC[2])})${fkC[3] ? ' ' + fkC[3].toUpperCase() : ''}${fkC[5] ? ' ' + fkC[5].toUpperCase() : ''};`);
      s = s.replace(RE_FK_INLINE, '').trim();
      if (!s) continue;
    }
    s = s.replace(/\bINTEGER\b/g, 'BIGINT')
         .replace(/\bINT\b/g, 'BIGINT')
         .replace(/\bREAL\b/g, 'DOUBLE PRECISION');
    const tm = s.match(/^([A-Za-z_0-9]+)([\s\S]*)$/);
    if (tm) s = q(tm[1]) + tm[2];
    keep.push(s);
  }
  criaTabelas.push(`CREATE TABLE ${q(nome)} (\n  ` + keep.join(',\n  ') + '\n);');
}

const idxSql = indices.map(i => {
  const s = i.sql.replace(/;\s*$/, '');
  const m = s.match(/^CREATE\s+(UNIQUE\s+)?INDEX\s+([A-Za-z_0-9]+)\s+ON\s+([A-Za-z_0-9]+)\s*\(([\s\S]+)\)$/i);
  if (!m) { console.log('!! índice não parseou: ' + s); return s + ';'; }
  return `CREATE ${m[1] || ''}INDEX ${q(m[2])} ON ${q(m[3])}(${qList(m[4])});`;
});

const arquivo = [
  '-- Schema PostgreSQL gerado do SQLite (GeraPro) — ferramenta da migração (Fase 1+)',
  '-- Gerado por: tools/migracao-postgres/traduzir-e-aplicar.js',
  '-- Tabelas: ' + criaTabelas.length + ' | FKs: ' + alterFks.length + ' | Índices: ' + idxSql.length,
  '',
  '-- ========== FASE 1: tabelas (sem FK) ==========',
  ...criaTabelas,
  '',
  '-- ========== FASE 2: chaves estrangeiras ==========',
  ...alterFks,
  '',
  '-- ========== FASE 3: índices ==========',
  ...idxSql,
  ''
].join('\n');
fs.writeFileSync(OUT, arquivo, 'utf8');
console.log('schema gerado: ' + OUT + ' (' + criaTabelas.length + ' tabelas, ' + alterFks.length + ' FKs, ' + idxSql.length + ' índices, ' + nAutoInc + ' identity)');

async function aplicar() {
  const c = new Client(PG_CONF);
  await c.connect();
  await c.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
  const falhas = [];
  for (const sql of criaTabelas) {
    try { await c.query(sql); } catch (e) { falhas.push('TABELA: ' + e.message + ' :: ' + sql.slice(0, 120)); }
  }
  for (const sql of alterFks) {
    try { await c.query(sql); } catch (e) { falhas.push('FK: ' + e.message + ' :: ' + sql.slice(0, 120)); }
  }
  for (const sql of idxSql) {
    try { await c.query(sql); } catch (e) { falhas.push('IDX: ' + e.message + ' :: ' + sql.slice(0, 120)); }
  }
  const tabs = await c.query("SELECT count(*) n FROM pg_tables WHERE schemaname='public'");
  const cols = await c.query("SELECT count(*) n FROM information_schema.columns WHERE table_schema='public'");
  const idxs = await c.query("SELECT count(*) n FROM pg_indexes WHERE schemaname='public'");
  console.log('FALHAS: ' + falhas.length);
  falhas.slice(0, 10).forEach(f => console.log('  - ' + f));
  console.log('VERIFICAÇÃO PG → tabelas: ' + tabs.rows[0].n + ' | colunas: ' + cols.rows[0].n + ' | índices: ' + idxs.rows[0].n);
  await c.end();
  if (falhas.length) process.exit(2);
}
aplicar().catch(e => { console.error('ERRO AO APLICAR:', e.message); process.exit(1); });
